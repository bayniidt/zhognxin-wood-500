function interpolate(value: string, variables?: Record<string, string>) {
  if (!variables) return value;
  return Object.entries(variables).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, replacement),
    value,
  );
}

const SPECIES_PHRASE = "okan. Dabema. Azobe. movingui (& other African hardwoods)";
const SPECIES_PATTERN = /(okoumé|okumé|okoume|okume|奥库梅)(?!\s+okan\.\s+Dabema\.\s+Azobe\.\s+movingui\s+\(&\s+other\s+African\s+hardwoods\))/giu;

export function appendSpeciesPhrase(value: string) {
  return value.replace(SPECIES_PATTERN, (match) => `${match} ${SPECIES_PHRASE}`);
}

type TranslationContextValue = {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: TranslationKey, variables?: Record<string, string>) => string;
};

const TranslationContext = createContext<TranslationContextValue | null>(null);
function getPageMeta(language: LanguageCode, pathname: string) {
  const dictionary = translations[language];
  if (pathname.startsWith("/about-us")) {
    return { title: appendSpeciesPhrase(dictionary.metaAboutTitle), description: appendSpeciesPhrase(dictionary.metaAboutDescription) };
  }
  if (pathname.startsWith("/contact")) {
    return { title: appendSpeciesPhrase(dictionary.metaContactTitle), description: appendSpeciesPhrase(dictionary.metaContactDescription) };
  }
  if (pathname.startsWith("/export-logistics")) {
    return { title: appendSpeciesPhrase(dictionary.metaExportTitle), description: appendSpeciesPhrase(dictionary.metaExportDescription) };
  }
  return { title: appendSpeciesPhrase(dictionary.metaHomeTitle), description: appendSpeciesPhrase(dictionary.metaHomeDescription) };
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  const [language, setLanguage] = useState<LanguageCode>("en");

  useEffect(() => {
    const selectedOption = LANGUAGE_OPTIONS.find((option) => option.code === language);
    if (selectedOption) document.documentElement.lang = selectedOption.htmlLang;

    const { title, description } = getPageMeta(language, pathname);
    document.title = title;
    const descriptionMeta = document.querySelector('meta[name="description"]');
    descriptionMeta?.setAttribute("content", description);
  }, [language, pathname]);

  const value = useMemo<TranslationContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, variables) => appendSpeciesPhrase(interpolate(translations[language][key], variables)),
    }),
    [language],
  );

  return <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>;
}

export function useTranslation() {
  const context = useContext(TranslationContext);
  if (!context) throw new Error("useTranslation must be used inside LanguageProvider");
  return context;
}
